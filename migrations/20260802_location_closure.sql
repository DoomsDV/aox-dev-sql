-- 3) ORDS: DELETE /locations/:id/closures/:closure_id
--------------------------------------------------------------------------------
BEGIN
    ORDS.define_template(
        p_module_name => 'hasel',
        p_pattern     => 'locations/:id/closures/:closure_id'
    );
    ORDS.define_handler(
        p_module_name => 'hasel',
        p_pattern     => 'locations/:id/closures/:closure_id',
        p_method      => 'DELETE',
        p_source_type => ords.source_type_plsql,
        p_source      => q'[
DECLARE
    v_status_code   NUMBER;
    v_response_body CLOB;
    v_delete_group  NUMBER := 0;
BEGIN
    BEGIN
        IF :delete_group IS NOT NULL AND LENGTH(TRIM(:delete_group)) > 0 THEN
            v_delete_group := TO_NUMBER(:delete_group);
        END IF;
    EXCEPTION
        WHEN OTHERS THEN v_delete_group := 0;
    END;

    pkg_aox_location_closure_api.pr_delete_closure(
        pi_auth_header   => owa_util.get_cgi_env('AUTHORIZATION'),
        pi_closure_id    => TO_NUMBER(:closure_id),
        pi_delete_group  => v_delete_group,
        po_status_code   => v_status_code,
        po_response_body => v_response_body
    );
    :status_code := v_status_code;
    owa_util.mime_header('application/json', TRUE);
    IF v_response_body IS NOT NULL THEN htp.prn(v_response_body); END IF;
END;
        ]'
    );
    COMMIT;
END;
