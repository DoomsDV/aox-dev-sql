-- 2) ORDS: GET /locations/:id/closures
--------------------------------------------------------------------------------
BEGIN
    ORDS.define_template(
        p_module_name => 'hasel',
        p_pattern     => 'locations/:id/closures'
    );
    ORDS.define_handler(
        p_module_name => 'hasel',
        p_pattern     => 'locations/:id/closures',
        p_method      => 'GET',
        p_source_type => ords.source_type_plsql,
        p_source      => q'[
DECLARE
    v_status_code   NUMBER;
    v_response_body CLOB;
BEGIN
    pkg_aox_location_closure_api.pr_list_closures(
        pi_auth_header   => owa_util.get_cgi_env('AUTHORIZATION'),
        pi_location_id   => TO_NUMBER(:id),
        pi_from_date     => :from_date,
        pi_to_date       => :to_date,
        po_status_code   => v_status_code,
        po_response_body => v_response_body
    );
    :status_code := v_status_code;
    owa_util.mime_header('application/json', TRUE);
    IF v_response_body IS NOT NULL THEN htp.prn(v_response_body); END IF;
END;
        ]'
    );
    ORDS.define_handler(
        p_module_name => 'hasel',
        p_pattern     => 'locations/:id/closures',
        p_method      => 'POST',
