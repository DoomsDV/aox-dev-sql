-- HAS-29 / HAS-32: catalogo de capabilities + defaults por rol + overrides org x rol.
-- Reversible: DROP TABLE org_role_capability / role_capability_default / capability
-- (en ese orden) y ORDS.DELETE_HANDLER de permissions/*.
--
-- Defaults = comportamiento real de staging (HAS-28):
--   * Recepcionista ve sucursales/servicios/especialidades pero NO las edita.
--   * Recepcionista SI crea/edita clientes y gestiona cobros/agenda/horarios.
--   * Profesional ve clientes propios; no crea ni edita.
--   * Addons clinicos ON para los 3 roles, gated por entitlement de org.
--   * permissions.manage siempre ON y locked para Admin.

BEGIN
    EXECUTE IMMEDIATE q'[
CREATE TABLE capability (
  id_capability          NUMBER GENERATED BY DEFAULT AS IDENTITY,
  code                   VARCHAR2(80) NOT NULL,
  group_code             VARCHAR2(40) NOT NULL,
  group_label            VARCHAR2(80) NOT NULL,
  label                  VARCHAR2(120) NOT NULL,
  description            VARCHAR2(400),
  kind                   VARCHAR2(20) DEFAULT 'ACTION' NOT NULL,
  sort_order             NUMBER DEFAULT 0 NOT NULL,
  requires_entitlement   VARCHAR2(80),
  is_locked              NUMBER(1,0) DEFAULT 0 NOT NULL,
  is_active              NUMBER(1,0) DEFAULT 1 NOT NULL,
  created_at             TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT pk_capability PRIMARY KEY (id_capability),
  CONSTRAINT uq_capability_code UNIQUE (code),
  CONSTRAINT chk_capability_kind CHECK (kind IN ('MENU', 'ACTION', 'ADDON')),
  CONSTRAINT chk_capability_active CHECK (is_active IN (0, 1)),
  CONSTRAINT chk_capability_locked CHECK (is_locked IN (0, 1))
)]';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE q'[
CREATE TABLE role_capability_default (
  id_role_capability_default NUMBER GENERATED BY DEFAULT AS IDENTITY,
  rol_id_role                NUMBER NOT NULL,
  cap_id_capability          NUMBER NOT NULL,
  is_granted                 NUMBER(1,0) DEFAULT 1 NOT NULL,
  created_at                 TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT pk_role_cap_default PRIMARY KEY (id_role_capability_default),
  CONSTRAINT uq_role_cap_default UNIQUE (rol_id_role, cap_id_capability),
  CONSTRAINT fk_rcd_role FOREIGN KEY (rol_id_role) REFERENCES role (id_role),
  CONSTRAINT fk_rcd_capability FOREIGN KEY (cap_id_capability) REFERENCES capability (id_capability),
  CONSTRAINT chk_rcd_granted CHECK (is_granted IN (0, 1))
)]';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
