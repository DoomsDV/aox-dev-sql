  updated_at             TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_by             NUMBER,
  CONSTRAINT pk_org_role_capability PRIMARY KEY (id_org_role_capability),
  CONSTRAINT uq_org_role_capability UNIQUE (org_id_organization, rol_id_role, cap_id_capability),
  CONSTRAINT fk_orc_org FOREIGN KEY (org_id_organization) REFERENCES organization (id_organization),
  CONSTRAINT fk_orc_role FOREIGN KEY (rol_id_role) REFERENCES role (id_role),
  CONSTRAINT fk_orc_capability FOREIGN KEY (cap_id_capability) REFERENCES capability (id_capability),
  CONSTRAINT chk_orc_granted CHECK (is_granted IN (0, 1))
)]';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
