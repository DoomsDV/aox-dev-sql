-- Defaults: Admin todos; Recepcionista y Profesional segun matriz HAS-28.
DECLARE
    v_admin NUMBER := pkg_aox_util.fn_rol('ADMIN');
    v_prof  NUMBER := pkg_aox_util.fn_rol('PROFESIONAL');
    v_recep NUMBER := pkg_aox_util.fn_rol('RECEPCIONISTA');

    PROCEDURE upsert_grant(pi_role_id NUMBER, pi_code VARCHAR2, pi_granted NUMBER) IS
        v_cap_id NUMBER;
    BEGIN
        SELECT id_capability INTO v_cap_id FROM capability WHERE code = pi_code;
        MERGE INTO role_capability_default t
        USING (SELECT pi_role_id AS role_id, v_cap_id AS cap_id FROM dual) s
        ON (t.rol_id_role = s.role_id AND t.cap_id_capability = s.cap_id)
        WHEN MATCHED THEN UPDATE SET t.is_granted = pi_granted
        WHEN NOT MATCHED THEN INSERT (rol_id_role, cap_id_capability, is_granted)
        VALUES (s.role_id, s.cap_id, pi_granted);
    END;
BEGIN
    FOR rec IN (SELECT code FROM capability WHERE is_active = 1) LOOP
        upsert_grant(v_admin, rec.code, 1);
        upsert_grant(v_recep, rec.code, 0);
        upsert_grant(v_prof, rec.code, 0);
    END LOOP;

    -- Recepcionista
    upsert_grant(v_recep, 'dashboard.view', 1);
    upsert_grant(v_recep, 'calendar.view', 1);
    upsert_grant(v_recep, 'calendar.manage', 1);
    upsert_grant(v_recep, 'customers.view', 1);
    upsert_grant(v_recep, 'customers.create', 1);
    upsert_grant(v_recep, 'customers.edit', 1);
    upsert_grant(v_recep, 'customers.export', 1);
    upsert_grant(v_recep, 'cobros.view', 1);
    upsert_grant(v_recep, 'cobros.manage', 1);
    upsert_grant(v_recep, 'services.view', 1);
    upsert_grant(v_recep, 'locations.view', 1);
    upsert_grant(v_recep, 'addons.odontogram', 1);
    upsert_grant(v_recep, 'addons.body_map', 1);
    upsert_grant(v_recep, 'specialties.view', 1);
    upsert_grant(v_recep, 'professionals.view', 1);
    upsert_grant(v_recep, 'professionals.manage', 1);
    upsert_grant(v_recep, 'schedules.view', 1);
    upsert_grant(v_recep, 'schedules.manage', 1);
    upsert_grant(v_recep, 'ajustes.view', 1);

    -- Profesional
    upsert_grant(v_prof, 'dashboard.view', 1);
    upsert_grant(v_prof, 'calendar.view', 1);
    upsert_grant(v_prof, 'calendar.manage', 1);
    upsert_grant(v_prof, 'customers.view', 1);
    upsert_grant(v_prof, 'customers.export', 1);
    upsert_grant(v_prof, 'services.view', 1);
    upsert_grant(v_prof, 'addons.odontogram', 1);
    upsert_grant(v_prof, 'addons.body_map', 1);
    upsert_grant(v_prof, 'schedules.view', 1);
    upsert_grant(v_prof, 'ajustes.view', 1);
END;
/
COMMIT;

