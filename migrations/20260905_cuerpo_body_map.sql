USING (
  SELECT 'FRONT_GENERIC' AS region_code, 'FRONT' AS view_code, 'Frente (general)' AS label, 1 AS sort_order FROM dual UNION ALL
  SELECT 'BACK_GENERIC', 'BACK', 'Espalda (general)', 1 FROM dual UNION ALL
  SELECT 'SIDE_GENERIC', 'SIDE', 'Lado (general)', 1 FROM dual UNION ALL
  SELECT 'FRONT_SHOULDER_L', 'FRONT', 'Hombro izquierdo', 10 FROM dual UNION ALL
  SELECT 'FRONT_SHOULDER_R', 'FRONT', 'Hombro derecho', 11 FROM dual UNION ALL
  SELECT 'FRONT_KNEE_L', 'FRONT', 'Rodilla izquierda', 20 FROM dual UNION ALL
  SELECT 'FRONT_KNEE_R', 'FRONT', 'Rodilla derecha', 21 FROM dual UNION ALL
  SELECT 'BACK_HIP_L', 'BACK', 'Cadera izquierda', 30 FROM dual UNION ALL
  SELECT 'BACK_HIP_R', 'BACK', 'Cadera derecha', 31 FROM dual UNION ALL
  SELECT 'SIDE_ANKLE_L', 'SIDE', 'Tobillo izquierdo', 40 FROM dual UNION ALL
  SELECT 'SIDE_ANKLE_R', 'SIDE', 'Tobillo derecho', 41 FROM dual
