-- Addon BODY_MAP (MERGE por code)
MERGE INTO ref_addon t
USING (
  SELECT 'BODY_MAP' AS code,
         'Cuerpo' AS name,
         'Mapa corporal, zoom de articulación y evolución por sesión.' AS short_description,
         'BODY_MAP' AS feature_code,
         59000 AS price_amount,
         'PYG' AS currency,
         'MONTHLY' AS billing_period,
         1 AS is_active,
         2 AS sort_order,
         1 AS requires_specialty_bridge
    FROM dual
) s
ON (t.code = s.code)
WHEN MATCHED THEN UPDATE SET
  t.name = s.name,
  t.short_description = s.short_description,
  t.feature_code = s.feature_code,
  t.price_amount = s.price_amount,
  t.currency = s.currency,
  t.billing_period = s.billing_period,
  t.is_active = s.is_active,
  t.sort_order = s.sort_order,
  t.requires_specialty_bridge = s.requires_specialty_bridge
WHEN NOT MATCHED THEN
  INSERT (id_addon, code, name, short_description, feature_code, price_amount, currency, billing_period, is_active, sort_order, requires_specialty_bridge)
  VALUES (
    (SELECT NVL(MAX(id_addon), 0) + 1 FROM ref_addon),
    s.code, s.name, s.short_description, s.feature_code, s.price_amount, s.currency, s.billing_period, s.is_active, s.sort_order, s.requires_specialty_bridge
  );
COMMIT;

MERGE INTO ref_addon_specialty t
USING (
  SELECT ra.id_addon AS rad_id_addon, os.id_org_specialty AS osp_id_org_specialty
    FROM ref_addon ra
    JOIN org_specialty os ON os.id_org_specialty IN (4, 6)
   WHERE ra.code = 'BODY_MAP'
) s
ON (t.rad_id_addon = s.rad_id_addon AND t.osp_id_org_specialty = s.osp_id_org_specialty)
WHEN NOT MATCHED THEN
  INSERT (rad_id_addon, osp_id_org_specialty)
  VALUES (s.rad_id_addon, s.osp_id_org_specialty);
COMMIT;

